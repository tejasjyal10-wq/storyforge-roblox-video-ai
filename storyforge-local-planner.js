// Deterministic StoryForge planner. It creates scene cards from text only; it is not AI.
function splitStoryIntoScenes(story) {
  const beats = String(story || '').replace(/\r/g, '').split(/(?<=[.!?])\s+|\n+/).map(x => x.trim()).filter(Boolean);
  const count = Math.max(5, Math.min(12, beats.length || 5));
  const scenes = [];
  const sourceCount = Math.min(count, beats.length);
  if (sourceCount) {
    for (let i = 0; i < sourceCount; i++) {
      const start = Math.floor(i * beats.length / sourceCount);
      const end = Math.floor((i + 1) * beats.length / sourceCount);
      const description = beats.slice(start, Math.max(start + 1, end)).join(' ');
      const lower = description.toLowerCase();
      const location = /forest|woods|tree/.test(lower) ? 'Forest' : /school|class|teacher/.test(lower) ? 'School' : /house|home|room/.test(lower) ? 'Home' : /mountain|hill/.test(lower) ? 'Mountains' : /river|lake|water/.test(lower) ? 'Waterfront' : /road|street|travel|walk/.test(lower) ? 'Road' : 'Story location';
      const action = /run|chase|escape/.test(lower) ? 'Characters move quickly through the scene' : /discover|find|reveal|notice/.test(lower) ? 'Characters discover something and react' : /talk|say|tell|ask|warn/.test(lower) ? 'Characters have a conversation' : 'Characters act according to this story beat';
      scenes.push({ number: scenes.length + 1, title: `Scene ${scenes.length + 1}`, location, action, description, dialogue: '', emotion: 'Curious', camera: 'Medium shot', characters: [], duration: 8, notes: 'Generated by the bundled local planner; review and edit.' });
    }
  }
  while (scenes.length < 5) scenes.push({ number: scenes.length + 1, title: `Scene ${scenes.length + 1}`, location: 'To be decided', action: 'Add a story event here', description: 'Planning placeholder. Add an event from your story; the local planner does not invent plot events.', dialogue: '', emotion: 'Neutral', camera: 'Medium shot', characters: [], duration: 8, notes: 'Placeholder, not generated story content.' });
  return scenes;
}
module.exports = { splitStoryIntoScenes };
